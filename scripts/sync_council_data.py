#!/usr/bin/env python3
"""Generate the council explorer's classic script from its session JSON files."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "assets/data"
INDEX = DATA / "council-sessions.json"
TARGET = ROOT / "assets/scripts/data/council-data.js"


def load_council():
    council = json.loads(INDEX.read_text(encoding="utf-8"))
    council["sessions"] = [
        json.loads((DATA / filename).read_text(encoding="utf-8"))
        for filename in council["sessions"]
    ]
    media = json.loads((DATA / "photo-sources.json").read_text(encoding="utf-8"))
    photos = media["council"]
    keys = {*photos["byTheme"].values(), *photos["byRecord"].values()}
    display_fields = ("path", "width", "height")
    council["photos"] = {
        **photos,
        "assets": {key: {field: media["assets"][key][field] for field in display_fields} for key in sorted(keys)},
    }
    return council


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check without writing")
    args = parser.parse_args()
    payload = json.dumps(load_council(), ensure_ascii=False, separators=(",", ":"), allow_nan=False)
    expected = (
        "// Generated by scripts/sync_council_data.py from the council and photo JSON files.\n"
        f"window.ABIKO_COUNCIL = {payload};\n"
    ).encode("utf-8")
    if args.check:
        if not TARGET.is_file() or TARGET.read_bytes() != expected:
            parser.exit(1, "Council data differs. Run python3 scripts/sync_council_data.py.\n")
    else:
        TARGET.write_bytes(expected)


if __name__ == "__main__":
    main()
